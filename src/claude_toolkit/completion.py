"""``ctk completion SHELL``: tab completion for bash, zsh, fish and PowerShell.

The scripts are generated from the command line parser itself, so a new command or option is
completed without anyone editing a list. They complete subcommands (and ``shoot``'s kinds), options and
the fixed choices of an argument; everything else falls back to the shell's own file completion.

    eval "$(ctk completion bash)"                     # ~/.bashrc
    source <(ctk completion zsh)                      # ~/.zshrc, after compinit
    ctk completion fish | source                      # ~/.config/fish/config.fish
    ctk completion powershell | Out-String | Invoke-Expression    # $PROFILE
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh", "fish", "powershell")


@dataclass
class Option:
    flags: tuple[str, ...]
    help: str
    takes_value: bool
    choices: tuple[str, ...] = ()


@dataclass
class Node:
    """A command (or a nested one such as ``shoot web``) with what can follow it."""

    path: str  # "" for ctk itself, "shoot", "shoot web"
    children: list[tuple[str, str]] = field(default_factory=list)  # (name, help)
    options: list[Option] = field(default_factory=list)
    choices: tuple[str, ...] = ()  # fixed values of a positional argument


def _summary(text: str | None) -> str:
    line = (text or "").strip().splitlines()[0] if (text or "").strip() else ""
    return line if len(line) <= 90 else line[:87] + "..."


def tree(parser: argparse.ArgumentParser, path: str = "") -> list[Node]:
    """Every command of the parser, depth first, as flat nodes."""
    node = Node(path)
    nodes = [node]
    nested: list[tuple[str, argparse.ArgumentParser]] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {choice.dest: choice.help for choice in action._choices_actions}
            for name, sub in action.choices.items():
                node.children.append((name, _summary(helps.get(name) or sub.description)))
                nested.append((f"{path} {name}".strip(), sub))
        elif action.option_strings:
            if action.help != argparse.SUPPRESS:
                node.options.append(
                    Option(
                        tuple(action.option_strings),
                        _summary(action.help),
                        action.nargs != 0,
                        tuple(str(c) for c in action.choices or ()),
                    )
                )
        elif action.choices:
            node.choices = tuple(str(c) for c in action.choices)
    for sub_path, sub in nested:
        nodes += tree(sub, sub_path)
    return nodes


def _words(node: Node) -> list[str]:
    return [name for name, _ in node.children] + list(node.choices)


def _flags(node: Node) -> list[str]:
    return [flag for option in node.options for flag in option.flags]


# --- bash -------------------------------------------------------------------------------------


def bash(nodes: list[Node]) -> str:
    def case(body: dict[str, str]) -> str:
        return "\n".join(f'        "{path}") {value} ;;' for path, value in body.items())

    words = {n.path: f'r="{" ".join(_words(n))}"' for n in nodes}
    flags = {n.path: f'r="{" ".join(_flags(n))}"' for n in nodes}
    children = {n.path: f'r="{" ".join(name for name, _ in n.children)}"' for n in nodes}
    values = {
        f"{n.path}|{flag}": f'r="{" ".join(option.choices)}"'
        for n in nodes
        for option in n.options
        if option.choices
        for flag in option.flags
    }
    return f"""# bash completion for ctk, generated by `ctk completion bash`
_ctk() {{
    local cur prev path="" w r i
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${{COMP_WORDS[i]}}"
        [[ "$w" == -* ]] && continue
        r=""
        case "$path" in
{case(children)}
        esac
        [[ " $r " == *" $w "* ]] || break
        path="${{path:+$path }}$w"
    done
    r=""
    case "$path|$prev" in
{case(values)}
    esac
    if [[ -z "$r" ]]; then
        if [[ "$cur" == -* ]]; then
            case "$path" in
{case(flags)}
            esac
        else
            case "$path" in
{case(words)}
            esac
        fi
    fi
    COMPREPLY=($(compgen -W "$r" -- "$cur"))
}}
complete -o default -o bashdefault -F _ctk ctk
"""


# --- zsh --------------------------------------------------------------------------------------


def _zsh_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def zsh(nodes: list[Node]) -> str:
    def entries(items: list[tuple[str, str]]) -> str:
        return " ".join(_zsh_quote(f"{name.replace(':', chr(92) + ':')}:{text}") for name, text in items)

    cases = []
    for n in nodes:
        options = [(flag, option.help) for option in n.options for flag in option.flags]
        cases.append(
            f'        "{n.path}")\n'
            f"            subs=({entries(n.children)})\n"
            f"            vals=({' '.join(_zsh_quote(c) for c in n.choices)})\n"
            f"            opts=({entries(options)}) ;;"
        )
    values = [
        f'        "{n.path}|{flag}") compadd -- {" ".join(_zsh_quote(c) for c in option.choices)}; return ;;'
        for n in nodes
        for option in n.options
        if option.choices
        for flag in option.flags
    ]
    return f"""#compdef ctk
# zsh completion for ctk, generated by `ctk completion zsh`
_ctk() {{
    local path="" i w
    local -a subs vals opts
    for ((i = 2; i < CURRENT; i++)); do
        w="${{words[i]}}"
        [[ "$w" == -* ]] && continue
        subs=()
        case "$path" in
{chr(10).join(f'            "{n.path}") subs=({" ".join(_zsh_quote(name) for name, _ in n.children)}) ;;' for n in nodes)}
        esac
        (( ${{subs[(Ie)$w]}} )) || break
        path="${{path:+$path }}$w"
    done
    case "$path|${{words[CURRENT-1]}}" in
{chr(10).join(values) if values else '        "__none__") ;;'}
    esac
    subs=() vals=() opts=()
    case "$path" in
{chr(10).join(cases)}
    esac
    if [[ "${{words[CURRENT]}}" == -* ]]; then
        _describe -t options 'option' opts
    else
        (( ${{#subs}} )) && _describe -t commands 'command' subs
        (( ${{#vals}} )) && compadd -- "${{vals[@]}}"
        (( ${{#subs}} + ${{#vals}} )) || _files
    fi
}}
if [[ "${{funcstack[1]}}" == _ctk ]]; then
    _ctk "$@"
else
    compdef _ctk ctk
fi
"""


# --- fish -------------------------------------------------------------------------------------


def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish(nodes: list[Node]) -> str:
    lines = ["# fish completion for ctk, generated by `ctk completion fish`", "complete -c ctk -e"]
    for n in nodes:
        parts = n.path.split()
        if not parts:
            condition = "__fish_use_subcommand"
        else:
            condition = "; and ".join(f"__fish_seen_subcommand_from {part}" for part in parts)
            if n.children:
                condition += "; and not __fish_seen_subcommand_from " + " ".join(name for name, _ in n.children)
        for name, text in n.children:
            lines.append(
                f"complete -c ctk -n {_fish_quote(condition)} -f -a {_fish_quote(name)} -d {_fish_quote(text)}"
            )
        for choice in n.choices:
            lines.append(f"complete -c ctk -n {_fish_quote(condition)} -f -a {_fish_quote(choice)}")
        for option in n.options:
            spec = ""
            for flag in option.flags:
                spec += f" -l {flag[2:]}" if flag.startswith("--") else f" -s {flag[1:]}"
            if option.takes_value:
                spec += " -r" + (f" -f -a {_fish_quote(' '.join(option.choices))}" if option.choices else "")
            lines.append(f"complete -c ctk -n {_fish_quote(condition)}{spec} -d {_fish_quote(option.help)}")
    return "\n".join(lines) + "\n"


# --- PowerShell -------------------------------------------------------------------------------


def _ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def powershell(nodes: list[Node]) -> str:
    def array(items: list[str]) -> str:
        return "@(" + ", ".join(_ps_quote(item) for item in items) + ")"

    entries = []
    for n in nodes:
        children = ", ".join(f"@({_ps_quote(name)}, {_ps_quote(text)})" for name, text in n.children)
        options = ", ".join(
            f"@({_ps_quote(flag)}, {_ps_quote(option.help)}, {array(list(option.choices))})"
            for option in n.options
            for flag in option.flags
        )
        entries.append(
            f"        {_ps_quote(n.path)} = @{{ children = @({children}); options = @({options}); "
            f"choices = {array(list(n.choices))} }}"
        )
    return (
        "# PowerShell completion for ctk, generated by `ctk completion powershell`\n"
        "Register-ArgumentCompleter -Native -CommandName ctk -ScriptBlock {\n"
        "    param($wordToComplete, $commandAst, $cursorPosition)\n"
        "    $tree = @{\n" + "\n".join(entries) + "\n    }\n"
        "    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })\n"
        "    if ($wordToComplete -ne '' -and $words.Count -gt 0) { $words = $words[0..($words.Count - 2)] }\n"
        "    $path = ''\n"
        "    foreach ($w in $words) {\n"
        "        if ($w.StartsWith('-')) { continue }\n"
        '        $next = if ($path) { "$path $w" } else { $w }\n'
        "        if ($tree.ContainsKey($next)) { $path = $next } else { break }\n"
        "    }\n"
        "    $node = $tree[$path]\n"
        "    $previous = if ($words.Count -gt 0) { $words[-1] } else { '' }\n"
        "    $candidates = @()\n"
        "    $valued = $node.options | Where-Object { $_[0] -eq $previous -and $_[2].Count -gt 0 }\n"
        "    if ($valued) { $candidates = $valued[2] | ForEach-Object { , @($_, $_) } }\n"
        "    elseif ($wordToComplete.StartsWith('-')) { $candidates = $node.options | ForEach-Object { , @($_[0], $_[1]) } }\n"
        "    else {\n"
        "        $candidates = @($node.children) + @($node.choices | ForEach-Object { , @($_, $_) })\n"
        "    }\n"
        '    $candidates | Where-Object { $_[0] -like "$wordToComplete*" } | ForEach-Object {\n'
        "        $tip = if ($_[1]) { $_[1] } else { $_[0] }\n"
        "        [System.Management.Automation.CompletionResult]::new($_[0], $_[0], 'ParameterValue', $tip)\n"
        "    }\n"
        "}\n"
    )


GENERATORS = {"bash": bash, "zsh": zsh, "fish": fish, "powershell": powershell}


def script(shell: str) -> str:
    from .cli import build_parser

    return GENERATORS[shell](tree(build_parser()))


def run(args) -> int:
    print(script(args.shell), end="")
    return 0
