import os
import shutil
import subprocess
import sys

import pytest

from claude_toolkit import cli, completion
from claude_toolkit.hooks import HOOKS

NODES = completion.tree(cli.build_parser())
POSIX = sys.platform != "win32"  # `bash` on a Windows runner may be WSL's, which can't see our paths


def run(args, script, **env):
    return subprocess.run(
        args, input=None, capture_output=True, text=True, encoding="utf-8", timeout=30,
        env={**os.environ, "CTK_SCRIPT": script, **env}, check=False,
    )  # fmt: skip


def bash_complete(line: str) -> list[str]:
    """What bash offers after `line` (a trailing space completes the next word)."""
    words = line.split(" ")
    code = (
        'eval "$CTK_SCRIPT"; COMP_WORDS=(' + " ".join(f"'{w}'" for w in words) + f"); COMP_CWORD={len(words) - 1}; "
        '_ctk; printf "%s\\n" "${COMPREPLY[@]}"'
    )
    done = run(["bash", "-c", code], completion.script("bash"))
    assert done.returncode == 0, done.stderr
    return done.stdout.split()


def test_the_tree_comes_from_the_parser_and_hides_suppressed_options():
    paths = {n.path for n in NODES}
    assert {"", "doctor", "relay", "completion", "shoot", "shoot web", "shoot sheet"} <= paths
    top = next(n for n in NODES if n.path == "")
    assert {"doctor", "runq", "sessions", "shoot", "relay", "completion", "hook"} <= {name for name, _ in top.children}
    assert all(text for _, text in top.children), "every command has a description"
    flags = {flag for n in NODES for o in n.options for flag in o.flags}
    assert "--root" not in flags, "suppressed options stay hidden"
    sessions = next(n for n in NODES if n.path == "sessions")
    assert "--compare" in {f for o in sessions.options for f in o.flags}
    assert next(n for n in NODES if n.path == "verify").choices == ("status", "run")
    assert next(n for n in NODES if n.path == "hook").choices == tuple(HOOKS)


@pytest.mark.parametrize("shell", completion.SHELLS)
def test_every_command_and_option_is_in_every_script(shell):
    text = completion.script(shell)
    for node in NODES:
        for name, _ in node.children:
            assert name in text, f"{shell}: {name}"
        for option in node.options:
            for flag in option.flags:
                assert flag.lstrip("-") in text, f"{shell}: {flag}"
    assert "--root" not in text and "generated by `ctk completion" in text


@pytest.mark.skipif(not POSIX or not shutil.which("bash"), reason="needs bash")
def test_bash_completes_commands_options_and_choices():
    every = [name for name, _ in next(n for n in NODES if n.path == "").children]
    assert sorted(bash_complete("ctk ")) == sorted(every)
    assert bash_complete("ctk ru") == ["runq"]
    assert bash_complete("ctk shoot ") == ["web", "godot", "desktop", "compare", "sheet"]
    assert bash_complete("ctk shoot w") == ["web"]
    assert {"--toolkit", "--json"} <= set(bash_complete("ctk doctor --"))
    assert set(bash_complete("ctk sessions --c")) == {"--csv", "--compare"}
    assert bash_complete("ctk verify ") == ["status", "run"]
    assert bash_complete("ctk hook ") == list(HOOKS)
    assert bash_complete("ctk libdocs --ecosystem ") == ["python", "node", "rust", "go"]
    assert "--baseline" in bash_complete("ctk shoot web --")
    assert bash_complete("ctk doctor ./pro") == [], "paths are left to the shell's own completion"
    assert bash_complete("ctk completion ") == list(completion.SHELLS)


@pytest.mark.skipif(not POSIX or not shutil.which("fish"), reason="needs fish")
def test_fish_completes_commands_and_options():
    def fish_complete(line: str) -> dict[str, str]:
        done = run(
            ["fish", "--no-config", "-c", f'eval "$CTK_SCRIPT" | source; complete -C "{line}"'],
            completion.script("fish"),
        )
        assert done.returncode == 0, done.stderr
        return {row.split("\t")[0]: row.split("\t")[1] if "\t" in row else "" for row in done.stdout.splitlines()}

    assert fish_complete("ctk ru") == {"runq": "run a command and print only failures, summary and log path"}
    assert set(fish_complete("ctk shoot ")) >= {"web", "godot", "sheet"}
    assert "--toolkit" in fish_complete("ctk doctor --")
    assert set(fish_complete("ctk verify ")) >= {"status", "run"}
    assert "doctor" not in fish_complete("ctk doctor "), "a command's name is not offered again after it"


@pytest.mark.skipif(not POSIX, reason="the shells are not on Windows runners")
@pytest.mark.parametrize(("shell", "check"), [("bash", ["-n"]), ("zsh", ["-n"]), ("fish", ["--no-execute"])])
def test_scripts_are_valid_syntax(shell, check):
    if not shutil.which(shell):
        pytest.skip(f"needs {shell}")
    done = subprocess.run(
        [shell, *check, "/dev/stdin"], input=completion.script(shell), capture_output=True, text=True, check=False
    )
    assert done.returncode == 0, done.stderr


@pytest.mark.skipif(not POSIX or not shutil.which("zsh"), reason="needs zsh")
def test_zsh_loads_the_completion_function():
    code = (
        'autoload -Uz compinit && compinit -u -d "$TMPDIR/zcomp" && eval "$CTK_SCRIPT" && print -r -- ${(k)_comps[ctk]}'
    )
    done = run(["zsh", "-f", "-c", code], completion.script("zsh"), TMPDIR=os.environ.get("TMPDIR", "/tmp"))
    assert done.returncode == 0, done.stderr
    assert done.stdout.strip() == "ctk"


POWERSHELL = shutil.which("pwsh") or shutil.which("powershell")


@pytest.mark.skipif(not POWERSHELL, reason="needs PowerShell")
def test_powershell_script_parses_and_completes():
    parse = (
        "$e = $null; $t = $null; "
        "[void][System.Management.Automation.Language.Parser]::ParseInput($env:CTK_SCRIPT, [ref]$t, [ref]$e); "
        "if ($e.Count) { $e | ForEach-Object { $_.Message }; exit 1 }"
    )
    done = run([POWERSHELL, "-NoProfile", "-Command", parse], completion.script("powershell"))
    assert done.returncode == 0, done.stdout + done.stderr
    complete = (
        "Invoke-Expression $env:CTK_SCRIPT; "
        "foreach ($line in 'ctk sh', 'ctk shoot w', 'ctk doctor --t', 'ctk verify ') { "
        '(TabExpansion2 $line $line.Length).CompletionMatches | ForEach-Object { "$line|$($_.CompletionText)" } }'
    )
    done = run([POWERSHELL, "-NoProfile", "-Command", complete], completion.script("powershell"))
    assert done.returncode == 0, done.stderr
    lines = set(done.stdout.splitlines())
    assert {
        "ctk sh|shoot",
        "ctk shoot w|web",
        "ctk doctor --t|--toolkit",
        "ctk verify |status",
        "ctk verify |run",
    } <= lines


def test_command_prints_the_script_and_rejects_other_shells(capsys):
    assert cli.main(["completion", "bash"]) == 0
    assert capsys.readouterr().out == completion.script("bash")
    with pytest.raises(SystemExit) as exit_:
        cli.main(["completion", "csh"])
    assert exit_.value.code == 2
